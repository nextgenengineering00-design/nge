import { promises as fs } from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourceRoot = path.join(root, "legacy-source");
const outputFile = path.join(root, "lib", "legacy-content.generated.ts");

async function collectHtml(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectHtml(absolute));
    else if (entry.isFile() && entry.name.endsWith(".html")) files.push(absolute);
  }
  return files;
}

const files = (await collectHtml(sourceRoot)).sort();
const content = {};
for (const file of files) {
  const key = path.relative(sourceRoot, file).replaceAll(path.sep, "/");
  content[key] = await fs.readFile(file, "utf8");
}

const output = `/* This file is generated by scripts/generate-legacy-content.mjs. */\n` +
  `export const legacyHtml: Record<string, string> = ${JSON.stringify(content)};\n`;

await fs.writeFile(outputFile, output, "utf8");
console.log(`Generated ${path.relative(root, outputFile)} from ${files.length} HTML files.`);
